            {"q": "هل هناك رسوم إضافية عند الاستعلام أو استخدام الخدمة؟", "a": "تختلف الرسوم حسب نوع الخدمة والشركة المقدمة لها؛ الاستعلام غالباً ما يكون مجانياً أو بقروش رمزية، ويفضل مراجعة الموقع الرسمي لمعرفة التسعيرة الحالية."},
